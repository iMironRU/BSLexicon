import { describe, expect, it } from 'vitest';
import { parseQuery } from '../src/query/parser/parse';

/**
 * Тесты SDBL-парсера — не проверяем структуру AST (это сгенерированный
 * ANTLR-код, сам себя проверяет), а проверяем что:
 *  1. Наши образцы валидных запросов парсятся без ошибок.
 *  2. Битые запросы возвращают ошибки с русскоязычным message.
 *  3. Стартовое правило — queryPackage (пакет запросов).
 */

const OK = (q: string) => {
  const r = parseQuery(q);
  if (!r.ok) throw new Error(`Ожидался успех, получены ошибки:\n${r.errors.map((e) => `${e.line}:${e.column} ${e.message}`).join('\n')}\nЗапрос:\n${q}`);
};

describe('parseQuery — базовые SELECT', () => {
  it('ВЫБРАТЬ * ИЗ Справочник.Номенклатура', () => {
    OK('ВЫБРАТЬ * ИЗ Справочник.Номенклатура');
  });

  it('несколько полей + алиас', () => {
    OK('ВЫБРАТЬ Ссылка, Наименование КАК Имя ИЗ Справочник.Номенклатура');
  });

  it('ГДЕ с И/ИЛИ', () => {
    OK(`
      ВЫБРАТЬ Наименование
      ИЗ Справочник.Номенклатура
      ГДЕ ПометкаУдаления = ЛОЖЬ И (Код = "001" ИЛИ Код = "002")
    `);
  });

  it('УПОРЯДОЧИТЬ ПО с ASC/DESC', () => {
    OK('ВЫБРАТЬ * ИЗ Справочник.Номенклатура УПОРЯДОЧИТЬ ПО Наименование УБЫВ');
  });
});

describe('parseQuery — соединения', () => {
  it('ЛЕВОЕ СОЕДИНЕНИЕ', () => {
    OK(`
      ВЫБРАТЬ Н.Наименование, К.Наименование КАК Контрагент
      ИЗ Документ.РасходнаяНакладная КАК Н
      ЛЕВОЕ СОЕДИНЕНИЕ Справочник.Контрагенты КАК К
      ПО Н.Контрагент = К.Ссылка
    `);
  });

  it('ВНУТРЕННЕЕ СОЕДИНЕНИЕ + ПРАВОЕ', () => {
    OK(`
      ВЫБРАТЬ 1
      ИЗ Справочник.Номенклатура КАК Н
      ВНУТРЕННЕЕ СОЕДИНЕНИЕ Справочник.Контрагенты КАК К ПО ИСТИНА
      ПРАВОЕ СОЕДИНЕНИЕ Справочник.Склады КАК С ПО ИСТИНА
    `);
  });
});

describe('parseQuery — агрегаты и группировка', () => {
  it('СУММА + СГРУППИРОВАТЬ ПО', () => {
    OK(`
      ВЫБРАТЬ Контрагент, СУММА(Товары.Сумма) КАК Итог
      ИЗ Документ.РасходнаяНакладная.Товары КАК Товары
      СГРУППИРОВАТЬ ПО Контрагент
    `);
  });

  it('ИМЕЮЩИЕ', () => {
    OK(`
      ВЫБРАТЬ Контрагент, КОЛИЧЕСТВО(*) КАК Кол
      ИЗ Документ.РасходнаяНакладная
      СГРУППИРОВАТЬ ПО Контрагент
      ИМЕЮЩИЕ КОЛИЧЕСТВО(*) > 1
    `);
  });
});

describe('parseQuery — виртуальные таблицы регистров', () => {
  it('Остатки(&Дата)', () => {
    OK(`
      ВЫБРАТЬ Склад, Номенклатура, КоличествоОстаток
      ИЗ РегистрНакопления.ОстаткиТоваров.Остатки(&Дата)
    `);
  });

  it('Обороты(&Начало, &Конец)', () => {
    OK(`
      ВЫБРАТЬ Номенклатура, КоличествоОборот
      ИЗ РегистрНакопления.ОстаткиТоваров.Обороты(&Начало, &Конец)
    `);
  });

  it('СрезПоследних(&Дата)', () => {
    OK(`
      ВЫБРАТЬ Номенклатура, Цена
      ИЗ РегистрСведений.ЦеныНоменклатуры.СрезПоследних(&Дата)
    `);
  });
});

describe('parseQuery — расширенные конструкции', () => {
  it('ВЫБОР КОГДА ... ТОГДА ... ИНАЧЕ ... КОНЕЦ', () => {
    OK(`
      ВЫБРАТЬ ВЫБОР
                 КОГДА ПометкаУдаления ТОГДА "Удалено"
                 ИНАЧЕ "Актив"
               КОНЕЦ КАК Статус
      ИЗ Справочник.Номенклатура
    `);
  });

  it('ОБЪЕДИНИТЬ ВСЕ', () => {
    OK(`
      ВЫБРАТЬ Ссылка ИЗ Справочник.Номенклатура
      ОБЪЕДИНИТЬ ВСЕ
      ВЫБРАТЬ Ссылка ИЗ Справочник.Контрагенты
    `);
  });

  it('ПОМЕСТИТЬ ВТ_Х + следующий запрос из ВТ', () => {
    OK(`
      ВЫБРАТЬ Ссылка ПОМЕСТИТЬ ВТ_Номенклатура ИЗ Справочник.Номенклатура;
      ВЫБРАТЬ * ИЗ ВТ_Номенклатура
    `);
  });

  it('ИТОГИ ПО', () => {
    OK(`
      ВЫБРАТЬ Контрагент, Сумма
      ИЗ Документ.РасходнаяНакладная
      ИТОГИ СУММА(Сумма) ПО ОБЩИЕ, Контрагент
    `);
  });

  it('параметр &Имя', () => {
    OK('ВЫБРАТЬ * ИЗ Справочник.Номенклатура ГДЕ Наименование = &Имя');
  });

  it('ВЫРАЗИТЬ КАК Справочник', () => {
    OK(`
      ВЫБРАТЬ ВЫРАЗИТЬ(Регистратор КАК Документ.РасходнаяНакладная).Номер
      ИЗ РегистрНакопления.ОстаткиТоваров
    `);
  });
});

describe('parseQuery — синтаксические ошибки', () => {
  it('пустая строка → ошибка', () => {
    const r = parseQuery('');
    expect(r.ok).toBe(false);
  });

  it('незакрытая скобка → ошибка', () => {
    const r = parseQuery('ВЫБРАТЬ (1 + 2 ИЗ Т');
    expect(r.ok).toBe(false);
    if (!r.ok) {
      expect(r.errors.length).toBeGreaterThan(0);
      // Хоть какое-то русскоязычное сообщение
      expect(r.errors.some((e) => /[а-я]/i.test(e.message))).toBe(true);
    }
  });

  it('лишний токен → ошибка с позицией', () => {
    const r = parseQuery('ВЫБРАТЬ , * ИЗ Т');
    expect(r.ok).toBe(false);
    if (!r.ok) {
      expect(r.errors[0].line).toBeGreaterThan(0);
      expect(r.errors[0].column).toBeGreaterThanOrEqual(0);
    }
  });

  it('непонятный символ → ошибка', () => {
    const r = parseQuery('ВЫБРАТЬ ~ ИЗ Т');
    expect(r.ok).toBe(false);
  });

  it('ошибка на второй строке даёт правильный номер строки', () => {
    const r = parseQuery('ВЫБРАТЬ *\nИЗ ,');
    expect(r.ok).toBe(false);
    if (!r.ok) {
      expect(r.errors[0].line).toBe(2);
    }
  });
});
