describe('Ошибки', () => {
  it('неизвестная таблица → runtime error', () => {
    const r = runQuery('ВЫБРАТЬ * ИЗ Справочник.НетТакого', fx);
    expect(r.ok).toBe(false);
    if (!r.ok) {
      expect(r.errors.some((e) => e.message.includes('не найдена'))).toBe(true);
    }
  });

  it('синтаксическая ошибка → parser error', () => {
    const r = runQuery('ВЫБРАТЬ ,', fx);
    expect(r.ok).toBe(false);
    if (!r.ok) {
      expect(r.errors.some((e) => e.stage === 'parser')).toBe(true);
    }
  });

  it('.Остатки на регистре сведений → отклоняется', () => {
    const r = runQuery('ВЫБРАТЬ * ИЗ РегистрСведений.ЦеныНоменклатуры.Остатки()', fx);
    expect(r.ok).toBe(false);
    if (!r.ok) {
      expect(r.errors.some((e) => /Остатки|регистр/i.test(e.message))).toBe(true);
    }
  });
});

describe('Виртуальные таблицы регистров накопления (#44)', () => {
  it('Остатки() без параметра — все движения зачтены', () => {
    const r = run(`
      ВЫБРАТЬ *
      ИЗ РегистрНакопления.ОстаткиТоваров.Остатки()
    `);
    // 6 групп (5 номенклатур на s_main + 1 на s_east)
    expect(r.rows.length).toBe(6);
    // Обязательные колонки: Склад, Номенклатура, КоличествоОстаток, СуммаОстаток
    expect(r.columns).toEqual(['Склад', 'Номенклатура', 'КоличествоОстаток', 'СуммаОстаток']);
    // Найдём n1 на s_main: 100 приход − 5 расход = 95
    const n1main = r.rows.find((row) => row[0] === 's_main' && row[1] === 'n1');
    expect(n1main?.[2]).toBe(95);
    // n1 на s_east: 50 приход − 10 расход = 40
    const n1east = r.rows.find((row) => row[0] === 's_east' && row[1] === 'n1');
    expect(n1east?.[2]).toBe(40);
  });

  it('Остатки(&Дата) на дату между начальным приходом и первым расходом', () => {
    const r = run(`
      ВЫБРАТЬ Номенклатура, КоличествоОстаток
      ИЗ РегистрНакопления.ОстаткиТоваров.Остатки(ДАТАВРЕМЯ(2024,1,10))
      ГДЕ Склад = "s_main"
    `);
    // Только приходы 2024-01-01: 5 позиций, все полные
    const n1 = r.rows.find((row) => row[0] === 'n1');
    expect(n1?.[1]).toBe(100);
    const n4 = r.rows.find((row) => row[0] === 'n4');
    expect(n4?.[1]).toBe(1000);
  });

  it('Остатки на дату до всех движений → пустой результат', () => {
    const r = run(`
      ВЫБРАТЬ *
      ИЗ РегистрНакопления.ОстаткиТоваров.Остатки(ДАТАВРЕМЯ(2023,12,31))
    `);
    expect(r.rows.length).toBe(0);
  });

  it('Обороты за январь — Приход/Расход/Оборот', () => {
    const r = run(`
      ВЫБРАТЬ Номенклатура, КоличествоПриход, КоличествоРасход, КоличествоОборот
      ИЗ РегистрНакопления.ОстаткиТоваров.Обороты(ДАТАВРЕМЯ(2024,1,1), ДАТАВРЕМЯ(2024,2,1))
      ГДЕ Склад = "s_main"
      УПОРЯДОЧИТЬ ПО Номенклатура
    `);
    const n1 = r.rows.find((row) => row[0] === 'n1');
    // Приход 100 (нач-остатки), Расход 5 (d1)
    expect(n1?.[1]).toBe(100);
    expect(n1?.[2]).toBe(5);
    expect(n1?.[3]).toBe(95);
  });

  it('Обороты за февраль — только один документ проведён', () => {
    const r = run(`
      ВЫБРАТЬ Номенклатура, КоличествоРасход
      ИЗ РегистрНакопления.ОстаткиТоваров.Обороты(ДАТАВРЕМЯ(2024,2,1), ДАТАВРЕМЯ(2024,3,1))
    `);
    // Только d2: n3=2, n5=500
    expect(r.rows.length).toBe(2);
    const total = r.rows.reduce((a, row) => a + (row[1] as number), 0);
    expect(total).toBe(502);
  });

  it('СУММА поверх Обороты — общий оборот', () => {
    const r = run(`
      ВЫБРАТЬ СУММА(КоличествоОборот) КАК ВсегоОборот
      ИЗ РегистрНакопления.ОстаткиТоваров.Обороты(ДАТАВРЕМЯ(2024,1,1), ДАТАВРЕМЯ(2024,4,1))
    `);
    expect(r.rows.length).toBe(1);
    // Приходы: 100+50+20+1000+2000+50 = 3220
    // Расходы: 5+3+200+2+500+10 = 720
    // Оборот: 3220 - 720 = 2500
    expect(r.rows[0][0]).toBe(2500);
  });

  it('ОстаткиИОбороты за февраль — нач/кон + оборот', () => {
    const r = run(`
      ВЫБРАТЬ
        Номенклатура,
        КоличествоНачальныйОстаток,
        КоличествоРасход,
        КоличествоКонечныйОстаток
      ИЗ РегистрНакопления.ОстаткиТоваров.ОстаткиИОбороты(ДАТАВРЕМЯ(2024,2,1), ДАТАВРЕМЯ(2024,3,1))
      ГДЕ Склад = "s_main" И Номенклатура = "n3"
    `);
    // n3 на s_main: до февраля = 20, оборот расход = 2, конечный = 18
    expect(r.rows.length).toBe(1);
    expect(r.rows[0][1]).toBe(20);
    expect(r.rows[0][2]).toBe(2);
    expect(r.rows[0][3]).toBe(18);
  });

  it('JOIN виртуальной Остатки со справочником — разыменование измерения', () => {
    const r = run(`
      ВЫБРАТЬ
        Н.Наименование КАК Товар,
        О.КоличествоОстаток КАК Кол
      ИЗ РегистрНакопления.ОстаткиТоваров.Остатки() КАК О
      ЛЕВОЕ СОЕДИНЕНИЕ Справочник.Номенклатура КАК Н
        ПО О.Номенклатура = Н.Ссылка
      ГДЕ Н.Наименование = "Молоток"
    `);
    // Молоток (n1) на s_main = 95, на s_east = 40
    const total = r.rows.reduce((a, row) => a + (row[1] as number), 0);
    expect(total).toBe(135);
  });

  it('Т.* по виртуальной — раскрывает КоличествоОстаток и т.п.', () => {
    const r = run(`
      ВЫБРАТЬ О.*
      ИЗ РегистрНакопления.ОстаткиТоваров.Остатки() КАК О
    `);
    expect(r.columns).toContain('КоличествоОстаток');
    expect(r.columns).toContain('СуммаОстаток');
    expect(r.columns).toContain('Склад');
    expect(r.columns).not.toContain('ВидДвижения'); // это исходное поле движений, не виртуалки
  });
});
